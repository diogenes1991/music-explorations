"""Unit tests for the music-poc interfaces, using synthetic fixtures.

Run from music-poc/:  python -m unittest discover -s tests -v
Fixtures are generated by scripts/synthesize_test_fixtures.py and live in
tests/fixtures/ (WAV + internal-rep JSON per fixture). These tests do not
need any downloaded dataset — that is the point: the interfaces are
testable before GuitarSet (still downloading in the background) arrives.
"""
import json
import os
import sys
import unittest
from fractions import Fraction

import numpy as np

sys.path.insert(0, os.path.join(os.path.dirname(__file__), "..", "src"))

from music_poc.audio import chunk_samples, chunk_wav_file, load_wav
from music_poc.internal import Chord, Note, Piece

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FIXTURES = os.path.join(ROOT, "tests", "fixtures")


def load_piece(name):
    with open(os.path.join(FIXTURES, f"{name}.json")) as f:
        return Piece.from_dict(json.load(f))


class TestWavMatchesInternal(unittest.TestCase):
    def test_duration_matches_internal_rep(self):
        for name in ("melody_guitar", "melody_viola", "chords_guitar",
                     "piece_10s", "melody_with_rests"):
            piece = load_piece(name)
            samples, sr = load_wav(os.path.join(FIXTURES, f"{name}.wav"))
            actual = len(samples) / sr
            self.assertAlmostEqual(actual, piece.total_seconds, places=2,
                                   msg=name)

    def test_json_roundtrip_preserves_notes_and_style(self):
        piece = load_piece("melody_guitar")
        again = Piece.from_dict(piece.to_dict())
        self.assertEqual(piece, again)
        self.assertTrue(all(e.style == "guitar-pluck"
                            for e in piece.events
                            if isinstance(e, Note)))

    def test_rests_are_silent(self):
        piece = load_piece("melody_with_rests")
        samples, sr = load_wav(os.path.join(FIXTURES, "melody_with_rests.wav"))
        # Second event is a 1-beat rest at 120 bpm = 0.5 s, starting at 0.5 s.
        rest = samples[int(0.5 * sr):int(1.0 * sr)]
        self.assertTrue(np.all(rest == 0), "rest segment should be silent")
        self.assertEqual(piece.events[1].frequency, 0.0)


class TestChunking(unittest.TestCase):
    def test_exact_10s_piece_chunks_cleanly(self):
        samples, sr = load_wav(os.path.join(FIXTURES, "piece_10s.wav"))
        self.assertEqual(len(chunk_samples(samples, sr, 10.0)), 1)
        self.assertEqual(len(chunk_samples(samples, sr, 5.0)), 2)
        # Chunking must not lose or duplicate samples.
        rejoined = np.concatenate(chunk_samples(samples, sr, 3.0))
        self.assertEqual(len(rejoined), len(samples))
        np.testing.assert_array_equal(rejoined, samples)

    def test_chunk_wav_file_writes_chunks(self):
        import tempfile
        with tempfile.TemporaryDirectory() as tmp:
            paths = chunk_wav_file(
                os.path.join(FIXTURES, "piece_10s.wav"), tmp, 5.0)
            self.assertEqual(len(paths), 2)
            for p in paths:
                s, sr = load_wav(p)
                self.assertAlmostEqual(len(s) / sr, 5.0, places=2)


class TestStyleContrast(unittest.TestCase):
    def test_same_melody_different_style_sounds_different(self):
        g, sr = load_wav(os.path.join(FIXTURES, "melody_guitar.wav"))
        v, _ = load_wav(os.path.join(FIXTURES, "melody_viola.wav"))
        self.assertEqual(len(g), len(v))
        self.assertFalse(np.array_equal(g, v))

    def test_guitar_decays_viola_sustains_on_a_long_note(self):
        # One 4-beat note at 120 bpm = 2 s. Guitar RMS should fall
        # markedly from the first to the second half; viola should not.
        from music_poc.synth import render_piece
        for style, should_decay in (("guitar-pluck", True),
                                    ("viola-bow", False)):
            piece = Piece(events=[Note(440.0, Fraction(4), style)],
                          tempo_bpm=120.0)
            w = render_piece(piece)
            half = len(w) // 2
            rms_first = float(np.sqrt(np.mean(w[:half] ** 2)))
            rms_second = float(np.sqrt(np.mean(w[half:] ** 2)))
            if should_decay:
                self.assertLess(rms_second, 0.5 * rms_first)
            else:
                self.assertGreater(rms_second, 0.5 * rms_first)


class TestValidation(unittest.TestCase):
    def test_chord_with_mismatched_durations_rejected(self):
        with self.assertRaises(ValueError):
            Chord([Note(440.0, Fraction(1), "guitar-pluck"),
                   Note(554.37, Fraction(2), "guitar-pluck")])

    def test_unknown_style_rejected_by_synth(self):
        from music_poc.synth import render_piece
        piece = Piece(events=[Note(440.0, Fraction(1), "mystery-style")])
        with self.assertRaises(ValueError):
            render_piece(piece)


if __name__ == "__main__":
    unittest.main()
